export function suggestedTime(prayers: { prayer: string; time: number }[], now = Date.now()): DuaTime {
  const at = (p: string) => prayers.find((x) => x.prayer === p)?.time;
  const dhuhr = at('dhuhr');
  const asr = at('asr');
  const isha = at('isha');
  const fajr = at('fajr');
  if (isha && now >= isha + 30 * 60_000) return 'sleep';
  if (fajr && now < fajr) return 'sleep';
  if (asr && now >= asr) return 'evening';
  if (dhuhr && now < dhuhr) return 'morning';
  const h = new Date(now).getHours();
  return h < 12 ? 'morning' : h < 21 ? 'evening' : 'sleep';
}

// ----- today's progress (on this iPhone) -----

const KEY = 'noor.duas.v1';

export interface DuaProgress {
  day: string;
  counts: Record<string, number>;
  amal: Record<string, boolean>;
  /** Days with all amal of the day done, for a gentle streak. */
  streak: number;
  lastFull: string;
}

const dayKey = (d = new Date()) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

export function loadProgress(): DuaProgress {
  const fresh: DuaProgress = { day: dayKey(), counts: {}, amal: {}, streak: 0, lastFull: '' };
  try {
    const raw = JSON.parse(localStorage.getItem(KEY) ?? 'null') as DuaProgress | null;
    if (!raw) return fresh;
    // Counts are per time of day: keep them only for today.
    return raw.day === dayKey() ? raw : { ...fresh, streak: raw.streak, lastFull: raw.lastFull };
  } catch {
    return fresh;
  }
}

export function saveProgress(p: DuaProgress) {
  try {
    localStorage.setItem(KEY, JSON.stringify(p));
  } catch {
    /* ignore */
  }
}

