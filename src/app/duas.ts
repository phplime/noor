/** Items for a tab — surahs in Quran order. */
export function duasFor(time: DuaTime): Dua[] {
  const list = DUAS.filter((d) => d.times.includes(time));
  return time === 'surah' ? [...list].sort((a, b) => (a.no ?? 0) - (b.no ?? 0)) : list;
}

