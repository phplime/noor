"""Build public/quran/* from the quran-json package (CC-BY-SA 4.0).

Each ayah: [arabic, bangla meaning, bangla pronunciation (generated by bn_translit.py)].

Arabic: Uthmani text (The Noble Qur'an Encyclopedia).
Bangla: Muhiuddin Khan, via tanzil.net (non-commercial use).

Usage: npm pack quran-json@3.1.2 && tar -xzf quran-json-3.1.2.tgz
       python3 scripts/build-quran.py package/dist/quran_bn.json
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from bn_translit import ayah_tr  # noqa: E402

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), '..', 'public', 'quran')
os.makedirs(out, exist_ok=True)
data = json.load(open(src, encoding='utf-8'))

# The KFGQPC text writes open tanween as U+0657/065E/0656, which common fonts
# draw as boxes; show the standard tanween marks instead (pronunciation is
# worked out from the original text).
DISPLAY = str.maketrans({'\u0657': '\u064b', '\u065e': '\u064c', '\u0656': '\u064d'})


def show(t):
    return t.translate(DISPLAY)


index = []
daily = []
for ch in data:
    n = ch['id']
    index.append({'n': n, 'ar': ch['name'], 'en': ch['transliteration'], 'bn': ch['translation'], 'type': ch['type'], 'ayahs': ch['total_verses']})
    tr = lambda v: ayah_tr(v['text'], v['id'] == 1 or (n == 42 and v['id'] == 2))
    verses = [[show(v['text']), v['translation'], tr(v)] for v in ch['verses']]
    json.dump({'n': n, 'v': verses}, open(os.path.join(out, f'{n}.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    for v in ch['verses']:
        if 40 <= len(v['text']) <= 150 and len(v['translation']) <= 220:
            daily.append({'s': n, 'a': v['id'], 'ar': show(v['text']), 'bn': v['translation'], 'tr': tr(v)})

# ~400 verses spread through the Qur'an for "Ayah of the day".
step = max(1, len(daily) // 400)
daily = daily[::step][:400]
json.dump(index, open(os.path.join(out, 'index.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
json.dump(daily, open(os.path.join(out, 'daily.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
print(len(index), 'surahs,', len(daily), 'daily verses')
